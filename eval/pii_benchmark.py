"""Offline, keyless recall/precision benchmark for the PII recognizers.

This module scores :func:`app.guardrails.recognizers.find_all` against the
synthetic corpus in ``eval/fixtures/pii_synthetic_corpus.jsonl``. It needs no
API key, no database, no LLM, and no network: the recognizers are pure functions
and the corpus is a committed fixture. Run it as::

    python -m eval.pii_benchmark

Matching rule
-------------
A prediction is a true positive **only when its ``(start, end, kind)`` triple
equals a labelled span exactly**. A prediction that covers the same characters
as a label but reports a different ``kind`` is a false positive for its own kind
and a false negative for the labelled kind; the same is true of any prediction
on a negative (unlabelled) record. No partial-credit or fuzzy matching is
applied, so the numbers mean exactly what they say.

Aggregates
----------
``micro`` sums true positives, labels and predictions across all kinds.
``macro`` is the unweighted mean of the per-kind rates; a kind with no labels
(recall) or no predictions (precision) is excluded from that average and its
unavailable rate is reported as ``null``.

Floors
------
The floors sit strictly below the first measurement (2026-10-05) to leave room
for benign drift while still failing on a real regression. They are not targets:

* ``MICRO_RECALL_FLOOR = 0.92`` -- measured 1.000; margin 0.08. Recognizer
  recall against a corpus built from the same author's known-good values should
  be perfect; the margin tolerates a wording change that hides one or two spans.
* ``MICRO_PRECISION_FLOOR = 0.92`` -- measured 1.000; margin 0.08. Any single
  false positive on a negative record must not sink the gate, but a systematic
  one will.
* ``MACRO_RECALL_FLOOR = 0.90`` and ``MACRO_PRECISION_FLOOR = 0.90`` -- measured
  1.000; margin 0.10. Macro weights a rare kind equally with a common one, so it
  is given slightly more slack than micro.
* ``MIN_NEGATIVE_RECORDS = 5`` -- the corpus must carry enough near-misses for
  precision to be meaningful; a corpus that drops its negatives fails the gate
  instead of silently reporting precision 1.0.

What this measures and does not
-------------------------------
It measures the recognizers against a corpus generated by the same author with
a fixed seed: a **self-consistency and regression check**, not a measurement of
real-world PII recall on messy human text. The labels are independent of the
recognizers (they are recorded when each known-good value is concatenated), and
the negatives are deliberate near-misses, so the number is meaningful as a
regression signal -- but it is not a field-recall estimate.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from app.guardrails.recognizers import find_all

EVAL_DIR = Path(__file__).resolve().parent
DEFAULT_FIXTURE = EVAL_DIR / "fixtures" / "pii_synthetic_corpus.jsonl"
RESULTS_FILE = EVAL_DIR / "results" / "pii_benchmark.json"

MICRO_RECALL_FLOOR = 0.92
MICRO_PRECISION_FLOOR = 0.92
MACRO_RECALL_FLOOR = 0.90
MACRO_PRECISION_FLOOR = 0.90
MIN_NEGATIVE_RECORDS = 5

REQUIRED_RECORD_KEYS = ("id", "text", "labels")


def load_corpus(path: Path | None = None) -> tuple[dict, list[dict]]:
    """Load the JSONL corpus, returning ``(header, records)``.

    The optional ``type == "header"`` first line carries provenance. Every other
    line must carry the required record keys. An empty corpus is an error.
    """
    fixture = Path(path) if path is not None else DEFAULT_FIXTURE
    if not fixture.is_file():
        raise FileNotFoundError(f"PII corpus not found: {fixture}")

    header: dict = {}
    records: list[dict] = []
    for line_number, line in enumerate(
        fixture.read_text(encoding="utf-8").splitlines(), start=1
    ):
        line = line.strip()
        if not line:
            continue
        try:
            obj = json.loads(line)
        except json.JSONDecodeError as exc:
            raise ValueError(
                f"{fixture.as_posix()}:{line_number}: invalid JSON: {exc}"
            ) from exc
        if obj.get("type") == "header":
            header = obj
            continue
        missing = [key for key in REQUIRED_RECORD_KEYS if key not in obj]
        if missing:
            raise ValueError(
                f"{fixture.as_posix()}:{line_number}: missing keys {missing}"
            )
        records.append(obj)

    if not records:
        raise ValueError(
            f"{fixture.as_posix()} has zero records; refusing to benchmark an "
            "empty corpus"
        )
    return header, records


def _keys(matches) -> set[tuple[int, int, str]]:
    return {(match.start, match.end, match.kind) for match in matches}


def evaluate(records: list[dict]) -> dict:
    """Recall/precision over the corpus, per kind and aggregated."""
    label_totals: dict[str, int] = {}
    prediction_totals: dict[str, int] = {}
    true_positives: dict[str, int] = {}
    total_predictions = 0
    total_labels = 0
    total_true_positives = 0
    negative_records = 0
    negative_records_with_matches = 0

    rows: list[dict] = []
    for record in records:
        labels = record.get("labels") or []
        label_keys = {(l["start"], l["end"], l["kind"]) for l in labels}
        predictions = find_all(record["text"])
        prediction_keys = _keys(predictions)

        for kind in {key[2] for key in label_keys}:
            label_totals[kind] = label_totals.get(kind, 0) + sum(
                1 for key in label_keys if key[2] == kind
            )
        for kind in {key[2] for key in prediction_keys}:
            prediction_totals[kind] = prediction_totals.get(kind, 0) + sum(
                1 for key in prediction_keys if key[2] == kind
            )
        for key in label_keys & prediction_keys:
            true_positives[key[2]] = true_positives.get(key[2], 0) + 1

        total_labels += len(label_keys)
        total_predictions += len(prediction_keys)
        total_true_positives += len(label_keys & prediction_keys)

        if not labels:
            negative_records += 1
            if predictions:
                negative_records_with_matches += 1

        rows.append(
            {
                "id": record.get("id"),
                "labels": sorted(label_keys),
                "predictions": sorted(prediction_keys),
            }
        )

    kinds = sorted(set(label_totals) | set(prediction_totals))
    per_kind: dict[str, dict] = {}
    recalls: list[float] = []
    precisions: list[float] = []
    for kind in kinds:
        labels_count = label_totals.get(kind, 0)
        predictions_count = prediction_totals.get(kind, 0)
        true_count = true_positives.get(kind, 0)
        false_negatives = labels_count - true_count
        false_positives = predictions_count - true_count
        recall = true_count / labels_count if labels_count else None
        precision = true_count / predictions_count if predictions_count else None
        if recall is not None:
            recalls.append(recall)
        if precision is not None:
            precisions.append(precision)
        per_kind[kind] = {
            "labels": labels_count,
            "predictions": predictions_count,
            "true_positives": true_count,
            "false_positives": false_positives,
            "false_negatives": false_negatives,
            "recall": recall,
            "precision": precision,
        }

    micro_recall = total_true_positives / total_labels if total_labels else None
    micro_precision = (
        total_true_positives / total_predictions if total_predictions else None
    )
    return {
        "totals": {
            "records": len(records),
            "labelled_spans": total_labels,
            "predictions": total_predictions,
            "true_positives": total_true_positives,
            "false_positives": total_predictions - total_true_positives,
            "false_negatives": total_labels - total_true_positives,
        },
        "negative_records": negative_records,
        "negative_records_with_matches": negative_records_with_matches,
        "micro": {"recall": micro_recall, "precision": micro_precision},
        "macro": {
            "recall": sum(recalls) / len(recalls) if recalls else None,
            "precision": sum(precisions) / len(precisions) if precisions else None,
        },
        "per_kind": per_kind,
        "rows": rows,
    }


def gate_failures(summary: dict) -> list[str]:
    """Return the floor breaches for an aggregate summary."""
    failures: list[str] = []
    records = int(summary.get("totals", {}).get("records") or 0)
    labels = int(summary.get("totals", {}).get("labelled_spans") or 0)
    if records == 0:
        failures.append("records: corpus has no records")
    if labels == 0:
        failures.append("labels: corpus has no labelled spans")

    negatives = int(summary.get("negative_records") or 0)
    if negatives < MIN_NEGATIVE_RECORDS:
        failures.append(
            f"negatives: {negatives} negative record(s); required "
            f"{MIN_NEGATIVE_RECORDS} for precision to be meaningful"
        )

    for name, floor in (
        ("micro_recall", MICRO_RECALL_FLOOR),
        ("micro_precision", MICRO_PRECISION_FLOOR),
        ("macro_recall", MACRO_RECALL_FLOOR),
        ("macro_precision", MACRO_PRECISION_FLOOR),
    ):
        section, metric = name.split("_", 1)
        value = summary.get(section, {}).get(metric)
        if value is None:
            failures.append(f"{name}: missing")
        elif float(value) < floor:
            failures.append(f"{name}: {float(value):.3f} < {floor:.2f}")
    return failures


def run(
    fixture: Path | None = None,
    output: Path | None = None,
) -> tuple[dict, list[str]]:
    # Resolve module constants at CALL time, never as default arguments.
    fixture = Path(fixture) if fixture is not None else DEFAULT_FIXTURE
    output = Path(output) if output is not None else RESULTS_FILE

    header, records = load_corpus(fixture)
    summary = evaluate(records)
    summary["fixture"] = fixture.as_posix()
    summary["provenance"] = header
    failures = gate_failures(summary)
    summary["gate"] = {
        "passed": not failures,
        "failures": failures,
        "floors": {
            "micro_recall": MICRO_RECALL_FLOOR,
            "micro_precision": MICRO_PRECISION_FLOOR,
            "macro_recall": MACRO_RECALL_FLOOR,
            "macro_precision": MACRO_PRECISION_FLOOR,
            "min_negative_records": MIN_NEGATIVE_RECORDS,
        },
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return summary, failures


def _format_rate(value) -> str:
    return "n/a" if value is None else f"{value:.3f}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Score the PII recognizers on the synthetic corpus, keyless."
    )
    parser.add_argument("--fixture", type=Path, default=None)
    parser.add_argument("--output", type=Path, default=None)
    args = parser.parse_args(argv)

    try:
        summary, failures = run(args.fixture, args.output)
    except (FileNotFoundError, ValueError) as exc:
        print(f"PII BENCHMARK FAILED: {exc}", file=sys.stderr)
        return 1

    micro = summary["micro"]
    macro = summary["macro"]
    print(
        f"PII benchmark: {summary['totals']['records']} record(s), "
        f"micro recall={_format_rate(micro['recall'])} "
        f"precision={_format_rate(micro['precision'])}, "
        f"macro recall={_format_rate(macro['recall'])} "
        f"precision={_format_rate(macro['precision'])}, "
        f"negatives={summary['negative_records']} "
        f"({summary['negative_records_with_matches']} matched)"
    )
    if failures:
        for failure in failures:
            print(f"PII BENCHMARK FAILED: {failure}")
        return 1
    print(
        "Floors passed. Results: "
        f"{(Path(args.output) if args.output else RESULTS_FILE).as_posix()}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
